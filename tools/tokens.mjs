// Generates the apps' design tokens from design/tokens.json, the single
// source. Run with `make tokens`; commit the output and never edit it by hand.
//
//   admin/src/styles/tokens.css
//   mobile/packages/sola_ui/lib/src/tokens/tokens.g.dart

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'));

const HEADER = 'GENERATED by tools/tokens.mjs from design/tokens.json. Do not edit.';

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const px = (value) => {
  const n = Number.parseFloat(value);
  if (Number.isNaN(n)) throw new Error(`Not a pixel value: ${value}`);
  return n;
};
const em = (value) => (value ? Number.parseFloat(value) : 0);
const ms = (value) => {
  const m = /^(\d+)ms$/.exec(value);
  if (!m) throw new Error(`Not a millisecond value: ${value}`);
  return Number(m[1]);
};

function resolveColors(tokens) {
  const byName = new Map(tokens.map((t) => [t.name, t.value]));
  const resolve = (value, seen = new Set()) => {
    const ref = /^\{(.+)\}$/.exec(value);
    if (!ref) return value.toLowerCase();
    if (seen.has(ref[1])) throw new Error(`Circular colour reference: ${ref[1]}`);
    if (!byName.has(ref[1])) throw new Error(`Unknown colour reference: ${ref[1]}`);
    return resolve(byName.get(ref[1]), new Set([...seen, ref[1]]));
  };
  return tokens.map((t) => ({ ...t, value: resolve(t.value) }));
}

const colors = resolveColors(source.color.tokens);
const textStyles = source.type.groups.flatMap((group) =>
  group.styles.map((style) => ({ ...style, family: group.family })),
);

function css() {
  const lines = [`/* ${HEADER} */`, '', ':root {'];
  for (const c of colors) lines.push(`  --${c.name}: ${c.value};`);
  lines.push('');
  lines.push(`  --font-sans: ${source.type.families.sans};`);
  lines.push(`  --font-mono: ${source.type.families.mono};`);
  for (const s of textStyles) {
    lines.push('');
    lines.push(`  --text-${s.name}-family: var(--font-${s.family});`);
    lines.push(`  --text-${s.name}-size: ${s.fontSize};`);
    lines.push(`  --text-${s.name}-line-height: ${s.lineHeight};`);
    lines.push(`  --text-${s.name}-weight: ${s.fontWeight};`);
    lines.push(`  --text-${s.name}-tracking: ${s.letterSpacing ?? '0'};`);
  }
  lines.push('');
  for (const group of [source.spacing, source.radius, source.size]) {
    for (const t of group.tokens) lines.push(`  --${t.name}: ${t.value};`);
  }
  lines.push('');
  for (const e of source.motion.easing) {
    lines.push(`  --${e.name}: cubic-bezier(${e.value.join(', ')});`);
  }
  for (const d of source.motion.durations) lines.push(`  --${d.name}: ${d.value};`);
  lines.push('}', '');
  return lines.join('\n');
}

function dartColor(hex) {
  const m = /^#([0-9a-f]{6})$/.exec(hex);
  if (!m) throw new Error(`Expected #rrggbb, got ${hex}`);
  return `Color(0xFF${m[1].toUpperCase()})`;
}

// Int literals where possible (the analyzer prefers them); fields that must
// be doubles are typed as such.
function dartNum(n) {
  return `${n}`;
}

// A `///` doc comment wrapped to the analyzer's 80-column limit.
function dartDoc(text, indent = '  ') {
  const width = 80 - indent.length - 4;
  const lines = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    if (line && line.length + 1 + word.length > width) {
      lines.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) lines.push(line);
  return lines.map((l) => `${indent}/// ${l}`);
}

function dart() {
  const out = [
    `// ${HEADER}`,
    '',
    "import 'package:flutter/animation.dart';",
    '',
  ];

  out.push('/// Colour tokens.', 'abstract final class SolaColors {');
  for (const c of colors) {
    out.push(...dartDoc(c.usage));
    out.push(`  static const ${camel(c.name)} = ${dartColor(c.value)};`);
  }
  out.push('}', '');

  const numeric = [
    ['SolaSpace', 'Spacing tokens (logical pixels).', source.spacing.tokens],
    ['SolaRadius', 'Corner radius tokens (logical pixels).', source.radius.tokens],
    ['SolaSize', 'Size tokens (logical pixels).', source.size.tokens],
  ];
  for (const [cls, doc, tokens] of numeric) {
    out.push(`/// ${doc}`, `abstract final class ${cls} {`);
    for (const t of tokens) {
      out.push(...dartDoc(t.usage));
      out.push(`  static const double ${camel(t.name)} = ${dartNum(px(t.value))};`);
    }
    out.push('}', '');
  }

  out.push('/// Motion tokens.', 'abstract final class SolaMotion {');
  for (const e of source.motion.easing) {
    out.push(...dartDoc(e.usage));
    out.push(`  static const ${camel(e.name)} = Cubic(${e.value.join(', ')});`);
  }
  for (const d of source.motion.durations) {
    out.push(...dartDoc(d.usage));
    out.push(
      `  static const ${camel(d.name)} = Duration(milliseconds: ${ms(d.value)});`,
    );
  }
  out.push('}', '');

  out.push(
    '/// A text style from the type scale, independent of any font family.',
    'final class SolaTextToken {',
    '  /// Creates a text token.',
    '  const new({',
    '    required this.fontSize,',
    '    required this.lineHeight,',
    '    required this.fontWeight,',
    '    required this.letterSpacingEm,',
    '    required this.mono,',
    '    required this.uppercase,',
    '  });',
    '',
    '  /// Font size in logical pixels.',
    '  final double fontSize;',
    '',
    '  /// Line height in logical pixels.',
    '  final double lineHeight;',
    '',
    '  /// Font weight, 100 to 900.',
    '  final int fontWeight;',
    '',
    '  /// Letter spacing as a fraction of the font size.',
    '  final double letterSpacingEm;',
    '',
    '  /// Whether the style uses the monospace family.',
    '  final bool mono;',
    '',
    '  /// Whether text in this style is set in uppercase.',
    '  final bool uppercase;',
    '}',
    '',
    '/// Type scale tokens.',
    'abstract final class SolaTextTokens {',
  );
  for (const s of textStyles) {
    out.push(...dartDoc(s.usage));
    out.push(`  static const ${camel(s.name)} = SolaTextToken(`);
    out.push(`    fontSize: ${dartNum(px(s.fontSize))},`);
    out.push(`    lineHeight: ${dartNum(px(s.lineHeight))},`);
    out.push(`    fontWeight: ${s.fontWeight},`);
    out.push(`    letterSpacingEm: ${dartNum(em(s.letterSpacing))},`);
    out.push(`    mono: ${s.family === 'mono'},`);
    out.push(`    uppercase: ${s.uppercase === true},`);
    out.push('  );');
  }
  out.push('}', '');
  return out.join('\n');
}

function write(relative, content) {
  const path = join(root, relative);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${relative}`);
}

write('admin/src/styles/tokens.css', css());
write('mobile/packages/sola_ui/lib/src/tokens/tokens.g.dart', dart());
